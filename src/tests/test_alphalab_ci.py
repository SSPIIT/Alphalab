class TestFeatureData:

    def test_all_factors_file_exists(self):
        """all_factors.parquet must exist after DVC repro."""
        assert FEATURES_PATH.exists(), \
            f"Missing: {FEATURES_PATH}. Run `dvc repro` to generate features."

    def test_all_factors_not_empty(self):
        """Feature file must have rows."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        assert len(df) > 0, "all_factors.parquet is empty"

    def test_all_factors_has_numeric_columns(self):
        """Must have at least 10 numeric factor columns."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        assert len(numeric_cols) >= 10, \
            f"Expected ≥10 numeric columns, got {len(numeric_cols)}: {numeric_cols}"

    def test_no_all_null_columns(self):
        """No factor column should be 100% null."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        numeric_cols = df.select_dtypes(include=[np.number]).columns
        for col in numeric_cols:
            null_rate = df[col].isna().mean()
            assert null_rate < 1.0, f"Column '{col}' is entirely null"

    def test_baseline_stats_file_exists(self):
        """baseline_stats.parquet must exist (generated by calculate_baseline.py)."""
        assert BASELINE_PATH.exists(), \
            f"Missing: {BASELINE_PATH}. Run `python src/monitoring/calculate_baseline.py`"

    def test_baseline_stats_has_required_columns(self):
        """Baseline must contain mean, std, p50, null_rate columns."""
        if not BASELINE_PATH.exists():
            pytest.skip("baseline_stats.parquet not present — skipping")
        df = pd.read_parquet(BASELINE_PATH)
        required = {"mean", "std", "p50", "null_rate", "p25", "p75"}
        missing = required - set(df.columns)
        assert not missing, f"Baseline stats missing columns: {missing}"

    def test_baseline_stats_not_empty(self):
        """Baseline must have at least 10 features."""
        if not BASELINE_PATH.exists():
            pytest.skip("baseline_stats.parquet not present — skipping")
        df = pd.read_parquet(BASELINE_PATH)
        assert len(df) >= 10, f"Expected ≥10 features in baseline, got {len(df)}"


