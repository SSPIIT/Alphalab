class TestMonitoring:

    def test_calculate_baseline_importable(self):
        """calculate_baseline module must import cleanly."""
        try:
            from monitoring.calculate_baseline import calculate_baseline, compute_baseline_stats
        except ImportError as e:
            pytest.fail(f"Cannot import calculate_baseline: {e}")

    def test_compute_baseline_stats_correctness(self):
        """compute_baseline_stats must produce correct mean and std."""
        from monitoring.calculate_baseline import compute_baseline_stats

        # Synthetic data with known stats
        df = pd.DataFrame({
            "date": pd.date_range("2024-01-01", periods=100),
            "momentum_rank": np.random.randn(100) * 10 + 50,
            "value_rank":    np.random.randn(100) * 5  + 30,
        })

        stats = compute_baseline_stats(df, ["momentum_rank", "value_rank"])

        assert "momentum_rank" in stats.index
        assert "value_rank" in stats.index
        assert "mean" in stats.columns
        assert "std" in stats.columns
        assert "p50" in stats.columns
        assert "null_rate" in stats.columns

        # Mean should be close to 50 for momentum_rank
        assert abs(stats.loc["momentum_rank", "mean"] - 50) < 5, \
            "Baseline mean deviates too much from expected value"

    def test_baseline_null_rate_zero_for_clean_data(self):
        """null_rate must be 0.0 for a column with no nulls."""
        from monitoring.calculate_baseline import compute_baseline_stats

        df = pd.DataFrame({
            "date":        pd.date_range("2024-01-01", periods=50),
            "clean_factor": np.ones(50),
        })
        stats = compute_baseline_stats(df, ["clean_factor"])
        assert stats.loc["clean_factor", "null_rate"] == 0.0

    def test_baseline_null_rate_nonzero_for_dirty_data(self):
        """null_rate must reflect actual missing fraction."""
        from monitoring.calculate_baseline import compute_baseline_stats

        arr = np.ones(100, dtype=float)
        arr[:20] = np.nan   # 20% nulls
        df = pd.DataFrame({
            "date":         pd.date_range("2024-01-01", periods=100),
            "dirty_factor": arr,
        })
        stats = compute_baseline_stats(df, ["dirty_factor"])
        assert abs(stats.loc["dirty_factor", "null_rate"] - 0.2) < 0.01


