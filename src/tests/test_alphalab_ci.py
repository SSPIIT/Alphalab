class TestDataValidation:

    def test_factor_values_are_finite(self):
        """Factor columns must not contain inf or -inf."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        numeric = df.select_dtypes(include=[np.number])
        inf_cols = [c for c in numeric.columns if np.isinf(numeric[c]).any()]
        assert not inf_cols, f"Infinite values found in columns: {inf_cols}"

    def test_factor_null_rate_acceptable(self):
        """No factor column should have >50% nulls."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        numeric = df.select_dtypes(include=[np.number])
        bad_cols = [(c, df[c].isna().mean()) for c in numeric.columns
                    if df[c].isna().mean() > 0.5]
        assert not bad_cols, \
            f"Columns with >50% nulls: {[(c, f'{r:.0%}') for c, r in bad_cols]}"

    def test_date_column_present(self):
        """Feature file must have a date column."""
        if not FEATURES_PATH.exists():
            pytest.skip("all_factors.parquet not present — skipping")
        df = pd.read_parquet(FEATURES_PATH)
        date_candidates = [c for c in df.columns if "date" in c.lower()]
        has_datetime_index = isinstance(df.index, pd.DatetimeIndex)
        assert date_candidates or has_datetime_index, \
            "No date column or DatetimeIndex found in all_factors.parquet"


